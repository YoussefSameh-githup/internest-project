import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TPL = ROOT / "internest_core" / "templates" / "components"
IMG = ROOT / "internest_core" / "static" / "img" / "brand"

PURPLE, VIOLET, CORAL, ORANGE, AMBER = "#6a4cff", "#9b5cf6", "#ff6a3d", "#ff8a1f", "#ffa53a"
HEAD_PURPLE = "#8b5cf6"
NAVY_INK = "#0b1e4d"

# ---------------------------------------------------------------- the mark (viewBox 0 0 120 100)
RIBBON = "M16 86L33.5 47C37.5 38 48.5 38 52.5 47L63 71C67 80 77.5 80 81.5 71L102.5 24"
STAR = "M111 1Q112.3 7.7 119 9Q112.3 10.3 111 17Q109.7 10.3 103 9Q109.7 7.7 111 1Z"


def mark_body(gid: str) -> str:
    return (f'<defs><linearGradient id="{gid}" x1="14" y1="0" x2="104" y2="0" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="{PURPLE}"/><stop offset=".45" stop-color="{VIOLET}"/>'
            f'<stop offset=".7" stop-color="{CORAL}"/><stop offset="1" stop-color="{ORANGE}"/></linearGradient></defs>'
            f'<path class="bm-ribbon" d="{RIBBON}" pathLength="1" fill="none" stroke="url(#{gid})" stroke-width="15" '
            f'stroke-linecap="round" stroke-linejoin="round"/>'
            f'<circle class="bm-head bm-head--a" cx="36" cy="21" r="9" fill="{HEAD_PURPLE}"/>'
            f'<circle class="bm-head bm-head--b" cx="84" cy="23" r="9" fill="{ORANGE}"/>'
            f'<path class="bm-star" d="{STAR}" fill="{AMBER}"/>')


# ---------------------------------------------------------------- the wordmark (x-height 16..40, caps from 8)
E_END = (12 + 12 * math.cos(math.radians(38)), 28 + 12 * math.sin(math.radians(38)))
GLYPHS = {
    "I": ("M0 8V40", 0),
    "n": ("M0 40V16M0 24A8 8 0 0 1 16 24V40", 16),
    "t": ("M4 8V33A7 7 0 0 0 11 40H12M0 17H11", 12),
    "e": (f"M0.5 28H23.5A11.5 11.5 0 1 0 {E_END[0]:.2f} {E_END[1]:.2f}", 24),
    "r": ("M0 40V16M0 27A11 11 0 0 1 11 16H12.5", 12.5),
    "s": ("M16.5 19.6C14.8 17.3 12.1 16 9 16C4.6 16 1.4 18.4 1.4 21.8C1.4 25.6 4.8 26.8 9 27.8C13.6 28.9 17.2 30.3 "
          "17.2 34.2C17.2 37.8 13.8 40 9.2 40C5.3 40 2.2 38.5 0.4 35.9", 17.6),
}
GAPS = {"default": 10, ("I", "n"): 10.5, ("t", "e"): 8, ("r", "n"): 9.5, ("e", "s"): 9, ("s", "t"): 7.5,
        ("n", "t"): 9, ("e", "r"): 9.5}
SW = 6.4  # bold, like the reference wordmark


def layout(text):
    out, x, prev = [], 0.0, None
    for ch in text:
        if prev is not None:
            x += GAPS.get((prev, ch), GAPS["default"])
        d, w = GLYPHS[ch]
        out.append((x, d))
        x += w
        prev = ch
    return out, x


def wordmark_groups(inter_ink: str, nest_ink: str = ORANGE) -> tuple[str, float]:
    glyphs, right = layout("Internest")
    def group(cls, items, ink):
        paths = "".join(f'<path transform="translate({x:.2f} 0)" d="{d}"/>' for x, d in items)
        return (f'<g class="{cls}" fill="none" stroke="{ink}" stroke-width="{SW}" stroke-linecap="round" '
                f'stroke-linejoin="round">{paths}</g>')
    return group("wm-inter", glyphs[:5], inter_ink) + group("wm-nest", glyphs[5:], nest_ink), right


# ---------------------------------------------------------------- outputs
def write(path: pathlib.Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT).as_posix())


wm_body, wm_right = wordmark_groups("currentColor")
pad = SW / 2 + 1
wm_box = f"{-pad:.1f} {8 - pad:.1f} {wm_right + 2 * pad:.1f} {32 + 2 * pad:.1f}"

write(TPL / "brand_mark.html",
      "{# Internest mark (generated by scripts/brand_assets.py; edit there). Pass a page-unique gid. #}"
      '<svg class="brand-mark {{ class|default:\'\' }}" viewBox="0 0 120 100" xmlns="http://www.w3.org/2000/svg" '
      'aria-hidden="true" focusable="false">'
      + mark_body("{{ gid|default:'bm' }}") + "</svg>\n")
write(TPL / "brand_wordmark.html",
      "{# Internest wordmark (generated by scripts/brand_assets.py). \"Inter\" follows currentColor, \"nest\" is orange. #}"
      f'<svg class="brand-wordmark {{{{ class|default:\'\' }}}}" viewBox="{wm_box}" xmlns="http://www.w3.org/2000/svg" '
      'aria-hidden="true" focusable="false">' + wm_body + "</svg>\n")

def hero_lockup() -> str:
    """The animated homepage lockup: mark + "Intern" | "nest" in ONE coordinate system.

    "Intern" (I n t e r n) and "nest" (n e s t) share their "n": in the final layout both n's sit on the same spot,
    so "Intern" + "nest" = "Internest". The CSS reveal flies each word out of its half of the N, holds them apart, then
    slides them together until the two n's coincide (the white one fades, the orange one stays, a spark marks the join).
    Distances travel as CSS variables in lockup units, so the choreography scales with the SVG on any screen.
    """
    glyphs, right = layout("Internest")
    # Stacked, like the official logo: the symbol above, the word below. Each word drops out of its own half of the N
    # (left leg / right arm) into its own half of the line, so the two paths never cross.
    mark_scale, sep, gap = 0.72, 15, 12
    word_x = sep + pad
    width = word_x + right + pad + sep
    mark_w, mark_h = 120 * mark_scale, 100 * mark_scale
    mark_x = (width - mark_w) / 2
    word_y = mark_h + gap - 8 + pad                   # glyph tops (y=8) sit `gap` below the mark
    n_x = glyphs[5][0]                                # the shared "n"
    intern_w, nest_w = n_x + 16, right - n_x
    intern_c = (word_x + intern_w / 2, word_y + 28)  # word centres in lockup units
    nest_c = (word_x + n_x + nest_w / 2, word_y + 28)
    leg = (mark_x + 30 * mark_scale, 62 * mark_scale)   # the N's purple left leg
    arm = (mark_x + 92 * mark_scale, 45 * mark_scale)   # the N's orange right arm
    height = word_y + 40 + pad + 2
    paths = lambda items: "".join(f'<path transform="translate({x:.2f} 0)" d="{d}"/>' for x, d in items)
    stroke = f'fill="none" stroke-width="{SW}" stroke-linecap="round" stroke-linejoin="round"'
    style = (f"--intern-from-x:{leg[0] - intern_c[0]:.1f}px;--intern-from-y:{leg[1] - intern_c[1]:.1f}px;"
             f"--nest-from-x:{arm[0] - nest_c[0]:.1f}px;--nest-from-y:{arm[1] - nest_c[1]:.1f}px;--sep:{sep}px")
    return ("{# Animated hero lockup (generated by scripts/brand_assets.py; edit there). Animation: static/css/landing.css. #}"
            f'<svg class="brand-lockup" viewBox="0 -2 {width:.1f} {height:.1f}" xmlns="http://www.w3.org/2000/svg" '
            f'aria-hidden="true" focusable="false" style="{style}">'
            f'<defs><radialGradient id="{{{{ gid }}}}Spark"><stop offset="0" stop-color="{AMBER}" stop-opacity=".95"/>'
            f'<stop offset="1" stop-color="{CORAL}" stop-opacity="0"/></radialGradient></defs>'
            f'<g class="bl-mark" transform="translate({mark_x:.1f} 0) scale({mark_scale})">' + mark_body("{{ gid }}") + "</g>"
            f'<g transform="translate({word_x:.1f} {word_y:.1f})">'
            f'<ellipse class="bl-spark" cx="{n_x + 8:.1f}" cy="28" rx="20" ry="20" fill="url(#{{{{ gid }}}}Spark)"/>'
            f'<g class="wm-intern" stroke="currentColor" {stroke}>{paths(glyphs[:5])}'
            f'<path class="wm-intern-n" transform="translate({glyphs[5][0]:.2f} 0)" d="{glyphs[5][1]}"/></g>'
            f'<g class="wm-nest" stroke="{ORANGE}" {stroke}>{paths(glyphs[5:])}</g>'
            "</g></svg>\n")


write(TPL / "brand_lockup_hero.html", hero_lockup())

