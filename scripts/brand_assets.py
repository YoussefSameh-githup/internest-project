"""Internest brand assets: one source for the mark (purple→orange N of two people reaching for a star) and the
stroke-drawn wordmark (no font needed, so it renders the same in every browser, e-mail and PNG).

    python scripts/brand_assets.py        # rewrites the files below

Writes
    internest_core/templates/components/brand_mark.html       inline SVG, {% include ... with gid="unique" %}
    internest_core/templates/components/brand_wordmark.html   inline SVG, "Inter" in currentColor, "nest" in orange
    internest_core/static/img/brand/internest-mark.svg        favicon / app icon source
    internest_core/static/img/brand/internest-logo-dark.svg   lockup for dark backgrounds
    internest_core/static/img/brand/internest-logo-light.svg  lockup for light backgrounds
PNG sizes (favicon, touch icon, Open Graph card) are rendered from these SVGs by scripts/brand_png.ps1.
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TPL = ROOT / "internest_core" / "templates" / "components"
IMG = ROOT / "internest_core" / "static" / "img" / "brand"

PURPLE, VIOLET, CORAL, ORANGE, AMBER = "#6a4cff", "#9b5cf6", "#ff6a3d", "#ff8a1f", "#ffa53a"
HEAD_PURPLE = "#8b5cf6"
NAVY_INK = "#0b1e4d"

# ---------------------------------------------------------------- the mark (viewBox 0 0 120 100)
RIBBON = "M16 86L33.5 47C37.5 38 48.5 38 52.5 47L63 71C67 80 77.5 80 81.5 71L102.5 24"
STAR = "M111 1Q112.3 7.7 119 9Q112.3 10.3 111 17Q109.7 10.3 103 9Q109.7 7.7 111 1Z"


def mark_body(gid: str) -> str:
    return (f'<defs><linearGradient id="{gid}" x1="14" y1="0" x2="104" y2="0" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="{PURPLE}"/><stop offset=".45" stop-color="{VIOLET}"/>'
            f'<stop offset=".7" stop-color="{CORAL}"/><stop offset="1" stop-color="{ORANGE}"/></linearGradient></defs>'
            f'<path class="bm-ribbon" d="{RIBBON}" pathLength="1" fill="none" stroke="url(#{gid})" stroke-width="15" '
            f'stroke-linecap="round" stroke-linejoin="round"/>'
            f'<circle class="bm-head bm-head--a" cx="36" cy="21" r="9" fill="{HEAD_PURPLE}"/>'
            f'<circle class="bm-head bm-head--b" cx="84" cy="23" r="9" fill="{ORANGE}"/>'
            f'<path class="bm-star" d="{STAR}" fill="{AMBER}"/>')


# ---------------------------------------------------------------- the wordmark (x-height 16..40, caps from 8)
E_END = (12 + 12 * math.cos(math.radians(38)), 28 + 12 * math.sin(math.radians(38)))
GLYPHS = {
    "I": ("M0 8V40", 0),
    "n": ("M0 40V16M0 24A8 8 0 0 1 16 24V40", 16),
    "t": ("M4 8V33A7 7 0 0 0 11 40H12M0 17H11", 12),
    "e": (f"M0.5 28H23.5A11.5 11.5 0 1 0 {E_END[0]:.2f} {E_END[1]:.2f}", 24),
    "r": ("M0 40V16M0 27A11 11 0 0 1 11 16H12.5", 12.5),
    "s": ("M16.5 19.6C14.8 17.3 12.1 16 9 16C4.6 16 1.4 18.4 1.4 21.8C1.4 25.6 4.8 26.8 9 27.8C13.6 28.9 17.2 30.3 "
          "17.2 34.2C17.2 37.8 13.8 40 9.2 40C5.3 40 2.2 38.5 0.4 35.9", 17.6),
}
GAPS = {"default": 10, ("I", "n"): 10.5, ("t", "e"): 8, ("r", "n"): 9.5, ("e", "s"): 9, ("s", "t"): 7.5,
        ("n", "t"): 9, ("e", "r"): 9.5}
SW = 6.4  # bold, like the reference wordmark


def layout(text):
    out, x, prev = [], 0.0, None
    for ch in text:
        if prev is not None:
            x += GAPS.get((prev, ch), GAPS["default"])
        d, w = GLYPHS[ch]
        out.append((x, d))
        x += w
        prev = ch
    return out, x


def wordmark_groups(inter_ink: str, nest_ink: str = ORANGE) -> tuple[str, float]:
    glyphs, right = layout("Internest")
    def group(cls, items, ink):
        paths = "".join(f'<path transform="translate({x:.2f} 0)" d="{d}"/>' for x, d in items)
        return (f'<g class="{cls}" fill="none" stroke="{ink}" stroke-width="{SW}" stroke-linecap="round" '
                f'stroke-linejoin="round">{paths}</g>')
    return group("wm-inter", glyphs[:5], inter_ink) + group("wm-nest", glyphs[5:], nest_ink), right


# ---------------------------------------------------------------- outputs
def write(path: pathlib.Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT).as_posix())


wm_body, wm_right = wordmark_groups("currentColor")
pad = SW / 2 + 1
wm_box = f"{-pad:.1f} {8 - pad:.1f} {wm_right + 2 * pad:.1f} {32 + 2 * pad:.1f}"

write(TPL / "brand_mark.html",
      "{# Internest mark (generated by scripts/brand_assets.py; edit there). Pass a page-unique gid. #}"
      '<svg class="brand-mark {{ class|default:\'\' }}" viewBox="0 0 120 100" xmlns="http://www.w3.org/2000/svg" '
      'aria-hidden="true" focusable="false">'
      + mark_body("{{ gid|default:'bm' }}") + "</svg>\n")
write(TPL / "brand_wordmark.html",
      "{# Internest wordmark (generated by scripts/brand_assets.py). \"Inter\" follows currentColor, \"nest\" is orange. #}"
      f'<svg class="brand-wordmark {{{{ class|default:\'\' }}}}" viewBox="{wm_box}" xmlns="http://www.w3.org/2000/svg" '
      'aria-hidden="true" focusable="false">' + wm_body + "</svg>\n")

dark_body, _ = wordmark_groups("#ffffff")
write(IMG / "wordmark-dark.svg",
      f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{wm_box}"><title>Internest</title>{dark_body}</svg>\n')
write(IMG / "internest-mark.svg",
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 100"><title>Internest</title>'
      + mark_body("g") + "</svg>\n")

# Horizontal lockup: mark (height 100 → 56) + wordmark (x-height row 16..40 → scaled ×1.5)
for theme, ink in (("dark", "#ffffff"), ("light", NAVY_INK)):
    body, right = wordmark_groups(ink)
    scale, mark_scale = 1.4, 0.7
    word_x = 120 * mark_scale + 14
    width = word_x + (right + pad) * scale + 4
    word_y = (100 * mark_scale) / 2 - 28 * scale  # the x-height centre (y=28) sits on the mark's centre
    write(IMG / f"internest-logo-{theme}.svg",
          f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:.1f} {100 * mark_scale:.0f}"><title>Internest</title>'
          f'<g transform="scale({mark_scale})">{mark_body("g" + theme)}</g>'
          f'<g transform="translate({word_x:.1f} {word_y:.1f}) scale({scale})">{body}</g></svg>\n')
