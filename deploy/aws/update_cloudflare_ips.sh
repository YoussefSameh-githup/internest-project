#!/usr/bin/env bash
# Writes /etc/nginx/conf.d/cloudflare-realip.conf from Cloudflare's published edge ranges, so that behind Cloudflare
# $remote_addr (and X-Real-IP, the rate limiter and the logs) is the visitor, not a Cloudflare edge.
# CF-Connecting-IP is honoured ONLY when the connection really comes from a listed Cloudflare range; a client that
# connects directly and sends the header is ignored. Harmless while the domain is not proxied by Cloudflare.
# It also writes /etc/nginx/conf.d/cloudflare-origin-guard.conf: $from_cloudflare = 1 only for a TCP peer in those
# ranges (or the box itself); the site config closes every other connection, so the origin cannot bypass Cloudflare.
#
# Fails safe: the last known-good files stay in place unless BOTH lists download, parse to well-formed CIDRs and
# reach a sane minimum (IPv4 >= CF_MIN_V4, IPv6 >= CF_MIN_V6), and the new files pass `nginx -t`. nginx is reloaded
# only after that test passes, and only when the ranges actually changed.
# Run as root, now and weekly (the ranges change rarely): sudo bash deploy/aws/update_cloudflare_ips.sh
set -euo pipefail
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin  # cron's PATH has no /usr/sbin (nginx)
umask 022

CONF_DIR=${CF_CONF_DIR:-/etc/nginx/conf.d}        # overridable for tests only
V4_URL=${CF_V4_URL:-https://www.cloudflare.com/ips-v4}
V6_URL=${CF_V6_URL:-https://www.cloudflare.com/ips-v6}
MIN_V4=${CF_MIN_V4:-10}                            # Cloudflare publishes 15 IPv4 and 7 IPv6 ranges (2026)
MIN_V6=${CF_MIN_V6:-4}
OUT=$CONF_DIR/cloudflare-realip.conf
GUARD=$CONF_DIR/cloudflare-origin-guard.conf
TMP=$(mktemp)
BDIR=$(mktemp -d)
trap 'rm -rf "$TMP" "$TMP.v4" "$TMP.v6" "$TMP.r4" "$TMP.r6" "$TMP.guard" "$BDIR"' EXIT

fail() { echo "$(date -u +%FT%TZ) $1; keeping the current files." >&2; exit 1; }

curl -fsS --max-time 20 "$V4_URL" -o "$TMP.v4" || fail "IPv4 list download failed"
curl -fsS --max-time 20 "$V6_URL" -o "$TMP.v6" || fail "IPv6 list download failed"

# Only well-formed CIDRs are kept: a bad or hijacked download cannot inject nginx directives.
tr -d '\r' < "$TMP.v4" | grep -E '^(25[0-5]|2[0-4][0-9]|1?[0-9]{1,2})(\.(25[0-5]|2[0-4][0-9]|1?[0-9]{1,2})){3}/([0-9]|[12][0-9]|3[0-2])$' > "$TMP.r4" || true
tr -d '\r' < "$TMP.v6" | grep -E '^[0-9a-fA-F:]*:[0-9a-fA-F:]*/([0-9]{1,2}|1[01][0-9]|12[0-8])$' > "$TMP.r6" || true
n4=$(wc -l < "$TMP.r4"); n6=$(wc -l < "$TMP.r6")
[ "$n4" -ge "$MIN_V4" ] || fail "only $n4 valid IPv4 ranges (need $MIN_V4)"
[ "$n6" -ge "$MIN_V6" ] || fail "only $n6 valid IPv6 ranges (need $MIN_V6)"

{
  echo "# Generated by deploy/aws/update_cloudflare_ips.sh. Do not edit by hand."
  sed 's/^/set_real_ip_from /; s/$/;/' "$TMP.r4" "$TMP.r6"
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

{
  echo "# Generated by deploy/aws/update_cloudflare_ips.sh. Do not edit by hand."
  echo "geo \$realip_remote_addr \$from_cloudflare {"
  echo "    default 0;"
  echo "    127.0.0.1 1;"
  echo "    ::1 1;"
  sed 's/^/    /; s/$/ 1;/' "$TMP.r4" "$TMP.r6"
  echo "}"
} > "$TMP.guard"

if cmp -s "$TMP" "$OUT" && cmp -s "$TMP.guard" "$GUARD"; then
  echo "$(date -u +%FT%TZ) Cloudflare ranges unchanged ($n4 IPv4, $n6 IPv6); nothing to do."
  exit 0
fi

for f in "$OUT" "$GUARD"; do if [ -f "$f" ]; then cp -p "$f" "$BDIR/"; fi; done
restore() {
  for f in "$OUT" "$GUARD"; do
    if [ -f "$BDIR/$(basename "$f")" ]; then cp -p "$BDIR/$(basename "$f")" "$f"; else rm -f "$f"; fi
  done
}
install -m 644 "$TMP" "$OUT"
install -m 644 "$TMP.guard" "$GUARD"
if nginx -t 2>/dev/null; then
  systemctl reload nginx || { restore; fail "nginx reload failed; previous files restored"; }
  echo "$(date -u +%FT%TZ) cloudflare-realip.conf + cloudflare-origin-guard.conf: $n4 IPv4 + $n6 IPv6 ranges, nginx reloaded."
else
  restore  # the running nginx still has the old config loaded, so no reload is needed
  fail "nginx -t failed with the new ranges; previous files restored"
fi
