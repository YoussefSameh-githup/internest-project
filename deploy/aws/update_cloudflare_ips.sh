#!/usr/bin/env bash
# Writes /etc/nginx/conf.d/cloudflare-realip.conf from Cloudflare's published edge ranges, so that behind Cloudflare
# $remote_addr (and X-Real-IP, the rate limiter and the logs) is the visitor, not a Cloudflare edge.
# CF-Connecting-IP is honoured ONLY when the connection really comes from a listed Cloudflare range; a client that
# connects directly and sends the header is ignored. Harmless while the domain is not proxied by Cloudflare.
# It also writes /etc/nginx/conf.d/cloudflare-origin-guard.conf: $from_cloudflare = 1 only for a TCP peer in those
# ranges (or the box itself); the site config closes every other connection, so the origin cannot bypass Cloudflare.
# Run as root, now and weekly (the ranges change rarely): sudo bash deploy/aws/update_cloudflare_ips.sh
set -euo pipefail
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin  # cron's PATH has no /usr/sbin (nginx)
umask 022

OUT=/etc/nginx/conf.d/cloudflare-realip.conf
GUARD=/etc/nginx/conf.d/cloudflare-origin-guard.conf
TMP=$(mktemp)
trap 'rm -f "$TMP" "$TMP.v4" "$TMP.v6" "$TMP.guard"' EXIT

curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4 -o "$TMP.v4"
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6 -o "$TMP.v6"

{
  echo "# Generated by deploy/aws/update_cloudflare_ips.sh on $(date -u +%F). Do not edit by hand."
  # Only well-formed CIDRs are written: a bad or hijacked download cannot inject nginx directives.
  grep -E '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$' "$TMP.v4" | sed 's/^/set_real_ip_from /; s/$/;/'
  grep -E '^[0-9a-fA-F:]+/[0-9]{1,3}$' "$TMP.v6" | sed 's/^/set_real_ip_from /; s/$/;/'
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

{
  echo "# Generated by deploy/aws/update_cloudflare_ips.sh on $(date -u +%F). Do not edit by hand."
  echo "geo \$realip_remote_addr \$from_cloudflare {"
  echo "    default 0;"
  echo "    127.0.0.1 1;"
  echo "    ::1 1;"
  grep '^set_real_ip_from' "$TMP" | sed 's/^set_real_ip_from /    /; s/;$/ 1;/'
  echo "}"
} > "$TMP.guard"

count=$(grep -c '^set_real_ip_from' "$TMP" || true)
if [ "$count" -lt 10 ]; then
  echo "Only $count Cloudflare ranges downloaded; keeping the current files." >&2
  exit 1
fi

bdir=$(mktemp -d)
for f in "$OUT" "$GUARD"; do if [ -f "$f" ]; then cp "$f" "$bdir/"; fi; done
install -m 644 "$TMP" "$OUT"
install -m 644 "$TMP.guard" "$GUARD"
if nginx -t 2>/dev/null; then
  systemctl reload nginx
  echo "cloudflare-realip.conf + cloudflare-origin-guard.conf: $count ranges, nginx reloaded."
else
  echo "nginx -t failed; restoring the previous files." >&2
  for f in "$OUT" "$GUARD"; do
    if [ -f "$bdir/$(basename "$f")" ]; then cp "$bdir/$(basename "$f")" "$f"; else rm -f "$f"; fi
  done
  nginx -t && systemctl reload nginx
  exit 1
fi
